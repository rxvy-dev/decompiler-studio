#!/usr/bin/env python3
"""Compile DsGhidra.java and install it as a tiny Ghidra module inside a Ghidra install.

    python build_helper.py <ghidra_install_dir> [path/to/javac]

Needs a JDK of the Java version Ghidra was built for (Ghidra 12.2: JDK 25). Only the build
machine needs the JDK; the finished app runs on the bundled JRE.
"""
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path


def main():
    if len(sys.argv) < 2:
        print(__doc__)
        return 2
    ghidra = Path(sys.argv[1]).resolve()
    javac = sys.argv[2] if len(sys.argv) > 2 else shutil.which("javac")
    if not javac:
        print("javac not found: install a JDK (25 for Ghidra 12.2) or pass its path.")
        return 1
    jar = Path(javac).resolve().with_name("jar.exe" if os.name == "nt" else "jar")
    here = Path(__file__).resolve().parent
    jars = [str(p) for p in (ghidra / "Ghidra").rglob("*.jar")]
    if not jars:
        print(f"{ghidra} does not look like a Ghidra install (no jars under Ghidra/).")
        return 1
    mod = ghidra / "Ghidra" / "Features" / "DecompilerStudio"
    with tempfile.TemporaryDirectory() as tmp:
        classes = Path(tmp) / "classes"
        classes.mkdir()
        subprocess.run([javac, "--release", "25", "-nowarn", "-cp", os.pathsep.join(jars),
                        "-d", str(classes), str(here / "DsGhidra.java")], check=True)
        (mod / "lib").mkdir(parents=True, exist_ok=True)
        (mod / "Module.manifest").write_text("")
        subprocess.run([str(jar), "cf", str(mod / "lib" / "ds-ghidra.jar"), "-C", str(classes), "."],
                       check=True)
    print(f"Installed {mod / 'lib' / 'ds-ghidra.jar'}")
    # Embed the jar in the app itself (helper_blob.py) so the app can repair an out-of-date copy on disk
    import base64
    import re
    ver = re.search(r'HELPER_VERSION = "([^"]+)"', (here / "DsGhidra.java").read_text()).group(1)
    data = base64.b64encode((mod / "lib" / "ds-ghidra.jar").read_bytes()).decode()
    lines = [data[i:i + 100] for i in range(0, len(data), 100)]
    (here.parent / "helper_blob.py").write_text(
        '"""Generated by ghidra_helper/build_helper.py: the compiled Ghidra helper, embedded in the app."""\n'
        f'VERSION = "{ver}"\nDATA = (\n' + "\n".join(f'    "{l}"' for l in lines) + "\n)\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
